#!/usr/bin/env python3
"""Generate docs/reference/{cli,config,errors,mcp}.md from the code.

The reference pages are not written by hand: the CLI page comes from the
argparse parser, the config page from ``settings_schema.SETTINGS``, the errors
page from ``errors.CATALOG`` and the MCP page from ``mcp_server.TOOLS``.  That
is what keeps them from drifting.

    python scripts/gen_docs.py            # rewrite the pages
    python scripts/gen_docs.py --check    # exit 1 (and say which) if any is stale

CI runs ``--check``; ``tests/test_docs.py`` does the same in the test suite.
"""

from __future__ import annotations

import argparse
import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from infoforge import cli, mcp_server  # noqa: E402
from infoforge import settings_schema as schema  # noqa: E402
from infoforge.errors import CATALOG, EXIT_OK, REASON_BY_EXIT  # noqa: E402

DOCS = ROOT / "docs" / "reference"
BANNER = ("<!-- Generated by scripts/gen_docs.py from the code. Do not edit by hand: "
          "run `python scripts/gen_docs.py`. -->\n")


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


# ----------------------------------------------------------------------- cli

def _subparsers(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _usage(prog: str, parser: argparse.ArgumentParser) -> str:
    parts = [prog]
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        if action.option_strings:
            flag = action.option_strings[-1]
            if action.nargs == 0:
                parts.append(f"[{flag}]")
            else:
                parts.append(f"[{flag} {action.metavar or action.dest.upper()}]")
        else:
            name = action.metavar or action.dest
            if action.choices:
                name = "{" + "|".join(action.choices) + "}"
            parts.append(f"{name} [{name} ...]" if action.nargs == "+" else name)
    return " ".join(parts)


def _options_table(parser: argparse.ArgumentParser) -> list[str]:
    rows = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction,
                               argparse._VersionAction)):
            continue
        if action.option_strings:
            name = ", ".join(f"`{o}`" for o in action.option_strings)
            if action.nargs != 0:
                name += f" `{action.metavar or action.dest.upper()}`"
        else:
            name = f"`{action.metavar or action.dest}`"
            if action.choices:
                name += " (" + " \\| ".join(f"`{c}`" for c in action.choices) + ")"
        default = ""
        if action.default not in (None, False, argparse.SUPPRESS):
            default = f"`{action.default}`"
        rows.append(f"| {name} | {_cell(action.help or '')} | {default} |")
    if not rows:
        return []
    return ["| Argument | Meaning | Default |", "|---|---|---|", *rows, ""]


def render_cli() -> str:
    parser = cli.build_parser()
    out = [BANNER, "# CLI reference", "",
           "`infoforge [--version] [--config PATH] <command> ...`", ""]
    out += ["## Global options", ""] + _options_table(parser)
    out += [
        "## Questions that start with a dash", "",
        "For `ask` and `search`, only the command's own flags (listed below) are flags; "
        "everything else is part of the question, so `infoforge search -5 degrees in "
        "kelvin` and `infoforge search --version` search for exactly that text. Flags may "
        "come before or after the question. A literal `--` ends flag parsing explicitly: "
        "`infoforge search --json --text -- \"-5 degrees\"`. Callers that pass user text "
        "should always put `--` before it.", "",
        "## Exit codes", "",
        "See [errors.md](errors.md) for the full table; in short: 0 ok, 1 doctor found a "
        "failing check, 2 config/usage/infrastructure, 3 no sources, 4 `--strict` "
        "uncited, 5 LLM unreachable, 6 not in the sources.", "",
    ]
    for name, sub in _subparsers(parser).items():
        out += [f"## `infoforge {name}`", "", (sub.description or
                                                _help_of(parser, name) or "").strip(), "",
                "```text", _usage(f"infoforge {name}", sub), "```", ""]
        out += _options_table(sub)
    return "\n".join(out).rstrip() + "\n"


def _help_of(parser: argparse.ArgumentParser, name: str) -> str:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for choice in action._choices_actions:
                if choice.dest == name:
                    return (choice.help or "").capitalize() + "."
    return ""


# -------------------------------------------------------------------- config

def render_config() -> str:
    out = [BANNER, "# Configuration reference", "",
           f"Schema version {schema.SCHEMA_VERSION}. The file is YAML at "
           "`$XDG_CONFIG_HOME/infoforge/config.yaml` (default "
           "`~/.config/infoforge/config.yaml`); `--config PATH` or `INFOFORGE_CONFIG` "
           "pick another. Every key can also be set from the environment as "
           "`INFOFORGE_<KEY>` (list-valued keys take a JSON list).", "",
           "Precedence, highest first: **command-line flag > environment variable > "
           "config file > default.** `infoforge config show` prints the effective "
           "values and which layer each came from; `infoforge config schema --json` "
           "prints this table as a JSON Schema.", ""]
    for group in dict.fromkeys(s.group for s in schema.SETTINGS):
        out += [f"## {group.capitalize()}", "",
                "| Key | Type | Default | Level | Environment | Meaning |",
                "|---|---|---|---|---|---|"]
        for s in (x for x in schema.SETTINGS if x.group == group):
            default = "*(required)*" if s.required else (
                "*(derived)*" if s.derived else f"`{s.default}`" if s.default != "" else "`\"\"`")
            if s.legacy_default is not schema.NO_LEGACY_DEFAULT:
                default += f" (a file that omits it: `{s.legacy_default}`)"
            kind = s.type + (f", {s.range_text()}" if s.range_text() else "")
            if s.secret:
                kind += ", secret"
            out.append(f"| `{s.key}` | {kind} | {default} | {s.level} | `{s.env}` | "
                       f"{_cell(s.description)} |")
        out.append("")
    out += ["## Ports", "",
            "InfoForge opens no listening port of its own. The kiwix container it manages "
            "publishes on `kiwix_bind:kiwix_port`. **8080 is the StudioForge panel's port**, "
            "so fresh configs use **8090**; a config file that omits `kiwix_port` keeps "
            "its 2.0 value of 8080 (set it explicitly if that collides).", ""]
    return "\n".join(out).rstrip() + "\n"


# -------------------------------------------------------------------- errors

def render_errors() -> str:
    out = [BANNER, "# Error catalog", "",
           "Every failure InfoForge reports is one row here. The **exit code** and "
           "**reason** are the stable contract scripts depend on (unchanged since 2.0); "
           "the **code** says precisely which problem it was and is what "
           "`--json` output carries as `error.code`.", "",
           "```json", '{"error": {"code": "kiwix_unreachable", "message": "...", '
           '"fix": "...", "docs": "docs/reference/errors.md#kiwix_unreachable"}}',
           "```", "",
           "## Exit codes and reasons", "", "| Exit | `reason` | Meaning |", "|---|---|---|"]
    meaning = {
        0: "Answered, grounded in retrieved sources.",
        2: "Config, usage or infrastructure error (see the codes below).",
        3: "Nothing relevant found; no answer was invented.",
        4: "`--strict`: the answer cited none of its sources.",
        5: "Every LLM endpoint was unreachable (sources are still printed).",
        6: "Articles were found but do not contain the answer.",
    }
    for exit_code, reason in REASON_BY_EXIT.items():
        out.append(f"| {exit_code} | `{reason}` | {meaning[exit_code]} |")
    out += ["| 1 | `error` | `infoforge doctor` found a failing check, or an unexpected crash. |",
            "| 130 | `error` | Interrupted (Ctrl-C). |", "",
            "## Codes", "", "| Code | Exit | Meaning |", "|---|---|---|"]
    for spec in CATALOG.values():
        out.append(f"| [`{spec.code}`](#{spec.code}) | {spec.exit} | {_cell(spec.summary)} |")
    out.append("")
    for spec in CATALOG.values():
        out += [f"### {spec.code}", "",
                f"- **Exit:** {spec.exit}" + ("" if spec.exit == EXIT_OK else
                                               f" (`reason`: `{spec.reason}`)"),
                f"- **What happened:** {spec.summary}",
                f"- **Message:** {spec.message.replace('{detail}', '<detail>')}",
                f"- **Fix:** {spec.fix}", ""]
    return "\n".join(out).rstrip() + "\n"


# ----------------------------------------------------------------------- mcp

def render_mcp() -> str:
    out = [BANNER, "# MCP server reference", "",
           "`infoforge-mcp` is a stdio MCP server (`pip install 'infoforge[mcp]'`). It exposes "
           "five **read-only** tools over the same library API as the CLI. It never creates "
           "or recreates the kiwix container, and has no tool for `serve` or `zimify`. "
           "Failures come back as `{\"ok\": false, \"exit_code\": ..., \"reason\": ..., "
           "\"error\": {code, message, fix, docs}}`; see [errors.md](errors.md).", "",
           "```json",
           '{"mcpServers": {"infoforge": {"command": "infoforge-mcp", '
           '"args": ["--config", "/path/to/config.yaml"]}}}',
           "```", "", "| Tool | Arguments | What it does |", "|---|---|---|"]
    for name, fn in mcp_server.TOOLS.items():
        params = []
        for p in inspect.signature(fn).parameters.values():
            ann = str(p.annotation).replace("<class '", "").replace("'>", "")
            default = "" if p.default is inspect.Parameter.empty else f" = {p.default!r}"
            params.append(f"`{p.name}: {ann}{default}`")
        doc = " ".join((fn.__doc__ or "").split())
        out.append(f"| `{name}` | {_cell(', '.join(params)) or '(none)'} | {_cell(doc)} |")
    out.append("")
    return "\n".join(out)


PAGES = {"cli.md": render_cli, "config.md": render_config,
         "errors.md": render_errors, "mcp.md": render_mcp}


def render_all() -> dict[str, str]:
    return {name: fn() for name, fn in PAGES.items()}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if any page is stale")
    args = ap.parse_args(argv)
    pages = render_all()
    stale = []
    for name, text in pages.items():
        path = DOCS / name
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            stale.append(name)
            if not args.check:
                DOCS.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.check:
        if stale:
            print("stale generated docs: " + ", ".join(stale) +
                  "\nrun: python scripts/gen_docs.py", file=sys.stderr)
            return 1
        print("docs/reference is up to date")
        return 0
    print("wrote: " + (", ".join(stale) if stale else "nothing (already current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
